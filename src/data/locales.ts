export function getLocalizedProject(project: Project, language: Language): LocalizedProject {
  const source = language === "en" ? englishProjects[project.slug] : undefined;
  return {
    ...project,
    kindLabel: language === "en" ? source?.kindLabel ?? project.kind : project.kind,
    title: source?.title ?? project.title,
    summary: source?.summary ?? project.summary,
    externalLabel: source?.externalLabel ?? project.externalLabel,
    facts: source?.facts ?? project.facts,
    caseStudy: source?.caseStudy ?? project.caseStudy,
  };
}
